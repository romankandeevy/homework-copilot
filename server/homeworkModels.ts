import { findSubjectByName } from '../src/lib/subjects.ts'

/* Модель под предмет, а не одна на всё.

   Пул был общий: первая модель списка решала и комбинаторику, и разбор
   слова. Но предметы просят разного. Геометрии нужен чертёж и короткий
   счёт, русскому - разбор слова, физике - подстановка в формулу, а
   комбинаторике - длинная цепочка со счётом случаев. Порядок моделей,
   годный для одного, для другого не оптимален ни по качеству, ни по цене.

   Поэтому у каждого предмета свой список. Голова - модель, которую мы
   считаем сильнейшей именно здесь. Дальше запасные: они нужны не «на
   всякий случай», а на отказ шлюза - когда ложится целое семейство,
   вызов должен уйти в другое (см. candidateModels).

   Что известно о моделях. Замер 5 сентября, вопрос без схемы решателя,
   две задачи с известным ответом (комбинаторика 9744 и 29/405, проверено
   перебором; ромб с диагоналями 10 и 24 - сторона 13 см):

     модель                    комбинаторика     геометрия    цена за вызов
     gemini-3-6-flash-openai   54 с, верно       10 с, верно  0,41 кр
     gpt-5-6-terra             69 с, верно       13 с, верно  1,01 кр
     gpt-5-6-sol               97 с, верно       10 с, верно  3,47 кр
     gpt-5-5                  132 с, верно        6 с, верно  12,00 кр
     gpt-5-6-luna             107 с, НЕВЕРНО     не мерил     дёшево
     grok-4-6                  сорвался          44 с, верно  0,74 кр

   Вопрос без схемы - не то же самое, что запрос решателя. Под полным
   решателем та же комбинаторика идёт иначе (замеры 5 и 6 сентября):

     gemini-3-6-flash-openai    45-57 с   то верно, то нет   0,74 кр
     gpt-5-6-terra                201 с   неверно            ~1 кр
     gpt-5-6-sol                   75 с   неверно            6,10 кр

   Кредит - примерно 0,5 ₽, решение стоит 5 ₽ (solutionPriceKopecks).
   Отсюда потолок: gpt-5-5 за 12 кредитов дороже самого решения и в пул не
   идёт ни на каком предмете, а gpt-5-6-sol за 6 кредитов на трудной задаче
   съедает больше половины цены - головой его ставить не за что.

   Кого нет и почему: claude-* - шлюз не доносит строгую схему (запрос с
   tools отвечает 503), формат решения держать нечем; grok-4-6 - на трудной
   задаче шлюз отдал HTML вместо ответа; gpt-5-6-luna - неверный ответ;
   gemini без суффикса -openai (кроме pro) строгую схему не принимает -
   gemini-2.5-flash отвечает «сервер на обслуживании».

   Порядок голов, кроме математики, выбран по свойствам моделей: замера по
   каждому из четырнадцати предметов у нас нет. Проверять - скриптом
   `node --experimental-strip-types scripts/probe-subject-models.mjs`,
   он гоняет полный запрос решателя по предмету и печатает время, ответ
   и цену вызова. */

/* Счётные предметы: длинная цепочка вычислений, где ошибка в середине
   уносит ответ целиком. Соблазн поставить сюда дорогую reasoning-модель
   проверен 6 сентября на той самой комбинаторике, полным решателем:

     gpt-5-6-sol               75 с · 6,10 кр ≈ 3,05 ₽ · 9024 - НЕВЕРНО
     gemini-3-6-flash-openai   45 с · 0,74 кр ≈ 0,37 ₽ · 8376 - НЕВЕРНО

   Верный ответ 9744. Дорогая модель ошиблась так же, как дешёвая, только
   вчетверо дороже. Поэтому голова здесь та же, что у остальных предметов,
   а дорогая модель стоит последней - на отказ шлюза.

   Задачи такого класса выбором модели не лечатся: три прогона дали три
   разных ответа (8616, 9024, 8376). Лечатся сверкой двух проходов - любая
   пара из этих трёх разошлась бы, и вместо неверного решения за деньги
   вышел бы честный отказ с возвратом. Это работа не пула. */
const countingModels = ['gemini-3-6-flash-openai', 'gemini-3-5-flash-openai', 'gpt-5-6-sol'] as const

/* Геометрия: цепочка короткая, зато нужен чертёж - сцена с точками,
   объектами и ограничениями. Её flash строит верно и за десять секунд,
   и именно на ней у нас больше всего живых проверок. */
const drawingModels = ['gemini-3-6-flash-openai', 'gpt-5-6-sol', 'gemini-3-5-flash-openai'] as const

/* Предметы слова: разбор, формулировка, факт, перевод. Считать почти нечего,
   и дорогая модель здесь не точнее - она только дольше и дороже. */
const wordModels = ['gemini-3-6-flash-openai', 'gemini-3-5-flash-openai', 'gpt-5-6-sol'] as const

/* Порядок моделей по предмету. Ключ - идентификатор из solvableSubjects:
   он же textbookId решения, так что предмет и модель связаны однозначно. */
export const homeworkModelsBySubject: Record<string, readonly string[]> = {
  // Комбинаторика, проценты, задачи на движение - разбор случаев.
  mathematics: countingModels,
  // Тождества, неравенства, прогрессии - цепочка преобразований.
  algebra: countingModels,
  // Планиметрия с чертежом.
  geometry: drawingModels,
  // Формула, подстановка с единицами, счёт в степенях десяти.
  physics: countingModels,
  // Уравнение реакции, моли, массовые доли.
  chemistry: countingModels,
  // Генетика и экология считаются в одно-два действия.
  biology: wordModels,
  // Системы счисления, кодирование, трассировка алгоритма.
  informatics: countingModels,
  // Разбор слова и предложения, орфография, пунктуация.
  russian: wordModels,
  literature: wordModels,
  english: wordModels,
  history: wordModels,
  social: wordModels,
  // Поясное время и масштаб - счёт короткий, остальное фактология.
  geography: wordModels,
  // Параллакс, звёздные величины, законы Кеплера.
  astronomy: countingModels,
}

/* Пул для незнакомого предмета. Первой стоит быстрая модель: неизвестный
   предмет с большей вероятностью словесный, чем счётный, - счётных у нас
   всего шесть из четырнадцати. */
export const defaultHomeworkModels = wordModels

// Одиночные вызовы вне решателя - ответ GET /api/solve.
export const defaultHomeworkModel = defaultHomeworkModels[0]

/* Порядок моделей для предмета. Принимает и название («Математика»), и
   идентификатор (`mathematics`): решателю приходит название, а в решении
   лежит уже textbookId. */
export function homeworkModelsForSubject(subject: string): readonly string[] {
  const byName = findSubjectByName(subject)
  const id = byName ? byName.id : subject.trim().toLocaleLowerCase('en-US')
  return homeworkModelsBySubject[id] ?? defaultHomeworkModels
}
