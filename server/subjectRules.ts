/** Образец записи для промпта: общие правила плюс предметный образец. */
export function subjectFormatPrompt(subject: string) {
  const known = findSubjectByName(subject)
  return [...commonFormat, ...(known ? formatBySubject[known.id] ?? [] : [])].join('\n')
}

export function subjectRules(subject: string): readonly SubjectRule[] {
  const known = findSubjectByName(subject)
  return [...(known ? rulesBySubject[known.id] ?? [] : []), ...commonRules]
}

/** Вопросы правил для промпта: модель отвечает на них до выдачи решения. */
export function subjectRuleQuestions(subject: string) {
  return subjectRules(subject).map((rule) => ({ id: rule.id, question: rule.question }))
}

/* Проверка правил кодом.

   Это и есть рецензент: там, где правило проверяемо, оно проверяется здесь
   и мгновенно. Правила без `verify` остаются требованием к модели и в
   замечания не попадают — иначе мы отвергали бы решение за то, чего сами
   не умеем проверить. */
export function verifySubjectRules(solution: HomeworkSolution): string[] {
  const issues: string[] = []

  for (const rule of subjectRules(solution.subject)) {
    if (!rule.verify) continue
    if (rule.applies && !rule.applies(solution)) continue
    const issue = rule.verify(solution)
    if (issue) issues.push(issue)
  }

  return [...new Set(issues)]
}

/* Признание модели «правило не выполнено».

   Модель сама отметила нарушенное правило и всё равно отдала решение - это
   признание, а не мнение, и спорить с ним не нужно. Но только там, где
   правило мы и сами проверяем: у правила без verify - «корни проверены»,
   «термины названы» - признание не проверить, а отвергать решение за то,
   чего мы сами не умеем проверить, нельзя (AGENTS.md). Аудит 16 сентября:
   такое признание отменяло решение вопреки этому правилу. */
export function verifyRuleAdmissions(
  solution: HomeworkSolution,
  checks: readonly { rule: string; passed: boolean }[],
): string[] {
  const verified = new Map(subjectRules(solution.subject)
    .filter((rule) => rule.verify && (!rule.applies || rule.applies(solution)))
    .map((rule) => [rule.id, rule]))
  return [...new Set(checks
    .filter((check) => !check.passed && verified.has(check.rule.trim()))
    .map((check) => `Правило предмета не выполнено: ${check.rule.trim()}`))]
}

/* Сверка ответа модели на вопросы правил с самой записью.

   Правило без verify кодом не проверяется, и модель могла ответить
   «ОДЗ выписана» в ruleChecks, не написав о ней ни строки. Где у правила
   есть явный след в записи, заявленное «выполнено» без этого следа -
   такое же нарушение, как прямая ошибка. */
export const ruleClaimIssuePrefix = 'Правило «'

/** Замечание о заявленном, но не видном в записи правиле - только это. */
export function isRuleClaimIssue(issue: string) {
  return issue.startsWith(ruleClaimIssuePrefix) && issue.includes('в записи этого не видно')
}

export function verifyRuleClaims(
  solution: HomeworkSolution,
  checks: readonly { rule: string; passed: boolean }[],
): string[] {
  const claimed = new Set(checks.filter((check) => check.passed).map((check) => check.rule.trim()))
  const written = `${solution.steps.join(' ')} ${solution.answer}`.toLocaleLowerCase('ru-RU').replaceAll('ё', 'е')
  const traced = (rule: SubjectRule) => (
    typeof rule.evidence === 'function' ? rule.evidence(solution) : rule.evidence?.test(written) === true
  )
  return subjectRules(solution.subject)
    .filter((rule) => rule.evidence && !rule.verify && claimed.has(rule.id))
    .filter((rule) => !rule.applies || rule.applies(solution))
    .filter((rule) => !traced(rule))
    .map((rule) => `${ruleClaimIssuePrefix}${rule.id}» отмечено выполненным, но в записи этого не видно: ${rule.question}`)
}
