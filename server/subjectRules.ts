/* Правила предмета вместо второго мнения модели.

   Рецензент — это третий вызов модели, и он шёл на каждой задаче: замер
   31 августа на проде показал 25–50 секунд из 43–78. Причина в том, что
   быстрый путь «два прохода сошлись» почти никогда не срабатывал, но и сама
   идея «спросить модель, всё ли хорошо» отвечает медленно и неточно.

   Школьные требования к записи — не предмет мнения. «В ответе есть единица
   измерения», «разбор по составу содержит корень», «уравнение реакции
   уравнено» проверяются кодом за микросекунды и всегда одинаково.

   Правила работают дважды. Сначала они уходят в промпт вопросами, на которые
   модель обязана ответить до выдачи решения и сама исправить нарушенное.
   Потом те, что проверяемы, проверяются здесь. Модель зовут ещё раз только
   когда правило нарушено, — а не «на всякий случай». */

export type SubjectRule = {
  id: string
  /** Вопрос, на который модель отвечает до выдачи решения. */
  question: string
  /** Когда правило вообще применимо к этой задаче. Нет — правило пропускается. */
  applies?: (solution: HomeworkSolution) => boolean
  /** Проверка кодом. Возвращает замечание или null. Нет проверки — правило только в промпте. */
  verify?: (solution: HomeworkSolution) => string | null
  /** След выполненного правила в записи. Нужен правилам без verify: по нему сверяется ответ модели в ruleChecks. */
  evidence?: RegExp | ((solution: HomeworkSolution) => boolean)
}

/* Приставка кратности - часть единицы: «252 кДж», «3 кН», «20 мА».
   Без неё «Q = 252 кДж» считался ответом без единицы измерения. Приставки
   разрешены только там, где школа их пишет: у граммов, метров и секунд
   свои сокращения уже перечислены ниже, а «кл» единицей быть не должно. */
const prefixedUnits = '(?:мк|[кмМГнд])?(?:Дж|Вт|Ом|Па|Гц|Н|В|А)'
/* Число с единицей измерения.

   Границу слова `\b` в конце ставить нельзя: словом она считает только
   латиницу с цифрами, и после кириллического «км» никакой границы нет —
   выражение молча переставало находить «12 км». Вместо неё запрет на
   продолжение буквой, чтобы «м» не срабатывало внутри «минут». */
const unitNames = `км\\/ч|м\\/с|г\\/моль|моль|мин|сут|руб|мм|мл|мг|км|кг|дм|см|°C|${prefixedUnits}|м|г|т|л|с|ч|°|%|₽`
const unitPattern = new RegExp(`\\d[\\d\\s.,]*\\s*(?:${unitNames})(?![а-яёa-z])`, 'iu')
// То же выражение для перебора всех величин условия, а не первой попавшейся.
const numberWithUnitPattern = new RegExp(unitPattern.source, 'giu')
/* Единица без числа перед ней: «Дж/(кг·°C)» в подстановке, «кДж» в ответе.
   Нужна там, где букву величины надо отличить от буквы единицы измерения. */
const bareUnitPattern = new RegExp(`(?<![\\p{L}])(?:${unitNames})(?![\\p{L}])`, 'giu')
const numberPattern = /\d/u

function text(solution: HomeworkSolution) {
  return [solution.answer, ...solution.steps].join(' ')
}

function conditionMentions(solution: HomeworkSolution, pattern: RegExp) {
  return pattern.test(solution.condition.toLocaleLowerCase('ru-RU').replaceAll('ё', 'е'))
}

/* Трёхграммное сходство строк.

   То же, чем движок сверяет условие, но местное: geometrySolutionEngine
   импортирует этот файл, и обратный импорт замкнул бы круг. Нужно, чтобы
   отличить «продолжение мысли» от «того же самого, переписанного ещё раз»:
   буквы и числа в пунктах меняются, форма остаётся. */
function similarity(left: string, right: string) {
  const normalize = (value: string) => value.toLocaleLowerCase('ru-RU').replace(/[^a-zа-яё0-9]+/giu, '')
  const grams = (value: string) => {
    const normalized = normalize(value)
    if (normalized.length < 3) return new Set([normalized])
    return new Set(Array.from({ length: normalized.length - 2 }, (_, index) => normalized.slice(index, index + 3)))
  }
  const leftGrams = grams(left)
  const rightGrams = grams(right)
  const overlap = [...leftGrams].filter((entry) => rightGrams.has(entry)).length
  return (2 * overlap) / Math.max(1, leftGrams.size + rightGrams.size)
}

function mentions(value: string, pattern: RegExp) {
  return pattern.test(value.toLocaleLowerCase('ru-RU').replaceAll('ё', 'е'))
}

/* Одно и то же число в разной записи.

   Аудит 16 сентября: правило «Дано собирает все числа условия» искало
   число буквально. «20 000 Дж» в условии и «Q = 20000 Дж» в «Дано»,
   «1.5 т» и «m = 1,5 т», «54 км/ч» и «v = 15 м/с» после перевода в СИ -
   всё это считалось потерянной величиной, хотя перевод в СИ правило само
   и требует. Сравниваем значения: запятая и точка, пробелы в тысячах,
   множитель «· 10³» и перевод единиц - кратные приставки, минуты, часы и
   километры в час. */
const superscriptToDigit: Record<string, string> = {
  '⁰': '0', '¹': '1', '²': '2', '³': '3', '⁴': '4', '⁵': '5', '⁶': '6', '⁷': '7', '⁸': '8', '⁹': '9', '⁻': '-',
}
const quantityNumber = /(-?\d{1,3}(?:[\s\u00a0]\d{3})+(?![\d.,])|-?\d+(?:[.,]\d+)?)(?:\s*[·×*]\s*10(?:\^\(?(-?\d+)\)?|([⁻⁰¹²³⁴⁵⁶⁷⁸⁹]+)))?/gu

export function numbersIn(value: string): number[] {
  return [...value.matchAll(quantityNumber)].map((match) => {
    const mantissa = Number(match[1].replace(/[\s\u00a0]/gu, '').replace(',', '.'))
    const power = match[2] ?? (match[3] ? [...match[3]].map((char) => superscriptToDigit[char] ?? '').join('') : '')
    return power ? mantissa * 10 ** Number(power) : mantissa
  }).filter((number) => Number.isFinite(number))
}

// Перевод единиц - кратные приставки, минуты, часы, сутки и км/ч в м/с.
const unitConversions = [1, 3.6, 60, 3600, 86400]
  .flatMap((factor) => [factor, 1 / factor])
  .flatMap((factor) => Array.from({ length: 19 }, (_, index) => factor * 10 ** (index - 9)))

function convertedQuantity(left: number, right: number) {
  if (left === 0 || right === 0) return false
  // Кельвины - сдвиг, а не множитель: 27 °C и 300 K.
  if (Math.abs(Math.abs(left - right) - 273.15) <= 0.15) return true
  const ratio = right / left
  return unitConversions.some((factor) => Math.abs(ratio / factor - 1) < 1e-3)
}

/* Какие величины условия не нашлись среди чисел «Дано».

   Каждое число «Дано» закрывает одну величину: сначала точные совпадения,
   потом переводы. Иначе «2 кг» закрыло бы и «20 °C» - двадцать в десять
   раз больше двух, и потерянная температура прошла бы как перевод.
   Одно и то же значение, названное в условии дважды, в «Дано» пишут один
   раз - поэтому значения условия берутся без повторов. */
export function missingQuantities(conditionValues: readonly number[], givenValues: readonly number[]) {
  const free = [...givenValues]
  const take = (index: number) => {
    free.splice(index, 1)
    return true
  }
  const unmatched = [...new Set(conditionValues)].filter((value) => {
    const exact = free.indexOf(value)
    return exact >= 0 ? !take(exact) : true
  })
  return unmatched.filter((value) => {
    const converted = free.findIndex((candidate) => convertedQuantity(value, candidate))
    return converted >= 0 ? !take(converted) : true
  })
}

