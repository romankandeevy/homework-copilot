// Один проход умной моделью вместо двух дешёвых и рецензента.
//
// Прежнее устройство: два независимых прохода дешёвыми моделями, сверка их
// ответов, а на расхождении — третий вызов, рецензент. Замер 4 сентября:
// геометрия 2,5 минуты, алгебра не уложилась и в три. Платили мы при этом
// за три-четыре вызова, а качество давала не сверка, а модель: два прохода
// слабой модели чаще сходились в одной и той же ошибке, чем ловили её.
//
// Теперь проход один и идёт сильнейшей моделью предмета. Освободившийся
// бюджет — и по деньгам, и по времени — уходит в неё же: подробный промпт,
// объяснение перед решением, разбор оформления. Проверка осталась там, где
// она объективна и мгновенна: правила предмета и разбор записи кодом
// (validateSolutionQuality, verifySubjectRules). Нарушенное чинится одним
// адресным повтором, а не разговором с ещё одной моделью.
//
// Какая модель сильнейшая — зависит от предмета: комбинаторику и физику
// держит reasoning-модель, разбор слова и датировку одинаково хорошо делает
// быстрая. Порядок моделей по предметам и замеры, на которых он собран, —
// в `homeworkModels.ts`.
export { defaultHomeworkModel, defaultHomeworkModels, homeworkModelsForSubject }

export type GeometrySolutionTraceEvent = {
  stage: 'author' | 'reviewer'
  candidate: EngineDraft
  approved: boolean
  issues: string[]
}

/* Стадия работы, о которой решателю есть что сообщить ученику. Это не
   раскадровка прогресса, а отметки фактических переходов: проходы запущены,
   проходы сошлись или отданы рецензенту. Ничего между ними мы не знаем и
   изображать не будем. */
export type HomeworkSolveStage = 'solving' | 'checking'

type EngineOptions = {
  apiKey: string
  model?: string
  fetchImpl?: typeof fetch
  onTrace?: (event: GeometrySolutionTraceEvent) => void
  onStage?: (stage: HomeworkSolveStage) => void
  /* Расход на один вызов модели. Шлюз возвращает его в теле ответа, и до
     сих пор мы его выбрасывали: себестоимость решения знали только по
     разовым замерам вручную (последний - 30 августа, на другом пуле).
     Теперь считает сам решатель, по каждому вызову. */
  onCost?: (event: HomeworkModelCall) => void
}

/* Один вызов модели: во что он обошёлся и чем кончился. */
export type HomeworkModelCall = {
  model: string
  /* Кредиты KIE. null - шлюз не сообщил расход в этом ответе. */
  credits: number | null
  seconds: number
  /* Для чего звали: черновик решения, план чертежа, починка. */
  purpose: string
  failed: boolean
}

type RuleCheck = {
  rule: string
  passed: boolean
  evidence: string
}

type EngineDraft = {
  ruleChecks: readonly RuleCheck[]
  condition: string
  taskType: HomeworkTaskType
  diagramRequired: boolean
  decisions: HomeworkDecisionSummary
  sourceVerified: boolean
  given: string[]
  goal: HomeworkSolution['goal']
  explanation: string[]
  steps: string[]
  /* Программа целиком: в строку тетради она не помещается. */
  code?: HomeworkSolution['code']
  answer: string
  /* Ответ в краткой проверяемой форме — только для сверки проходов между
     собой. Ученику он не показывается: в тетради стоит `answer`. */
  answerKey: string
  /* Черновик счёта: выражение и его результат на каждое вычисление. В
     тетрадь не идёт - его считает наш калькулятор и ловит потерянный
     множитель, который модель за собой не видит (см. worksheet.ts). */
  worksheet: WorksheetLine[]
  diagram: HomeworkDiagram
  analysis?: HomeworkWrittenAnalysis
}

type ReviewResult = {
  approved: boolean
  issues: string[]
  solution: EngineDraft
}

