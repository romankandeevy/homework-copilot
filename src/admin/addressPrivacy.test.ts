import { describe, expect, it } from 'vitest'
import { fraudExplanation, maskAddresses } from './addressPrivacy'

describe('адреса в админке', () => {
  it('флаг «с одного адреса» говорит о совпадении, а не об адресе', () => {
    expect(fraudExplanation('С адреса 10.0.0.1 за 24 ч зарегистрировано 3 аккаунтов'))
      .toBe('Совпадает адрес (хэш): за 24 ч зарегистрировано 3 аккаунтов')
    expect(fraudExplanation('С адреса 2001:db8::1 за 24 ч зарегистрировано 4 аккаунтов'))
      .toBe('Совпадает адрес (хэш): за 24 ч зарегистрировано 4 аккаунтов')
  })

  it('прячет IPv4 и IPv6 в любом тексте и не трогает остальное', () => {
    expect(maskAddresses('вход с 185.126.65.177 и ::ffff:10.0.0.2')).toBe('вход с адрес скрыт и адрес скрыт')
    expect(maskAddresses('2001:0db8:85a3:0000:0000:8a2e:0370:7334')).toBe('адрес скрыт')
    expect(fraudExplanation('Стартовые 50 ₽ потрачены за 3 мин после регистрации')).toBe('Стартовые 50 ₽ потрачены за 3 мин после регистрации')
    expect(maskAddresses('в 14:03:27 версия 1.2.3')).toBe('в 14:03:27 версия 1.2.3')
  })
})
