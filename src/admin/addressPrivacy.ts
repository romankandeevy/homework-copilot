/* IP в админке не показываем. База хранит адреса для антифрода и пределов,
   но человеку за пультом достаточно знать, что адрес совпал: сам адрес -
   персональные данные ученика. Антифрод пишет адрес прямо в текст флага
   («С адреса 10.0.0.1 …») и в улики (`evidence.ip`), поэтому текст чистим
   здесь, до вывода. */

export const SAME_ADDRESS = 'совпадает адрес (хэш)'

const ipv6 = /(?<![\w:.])(?:(?:[0-9a-f]{1,4}:){7}[0-9a-f]{1,4}|(?:[0-9a-f]{1,4}:){0,6}[0-9a-f]{0,4}::(?:[0-9a-f]{1,4}:){0,6}[0-9a-f]{0,4})(?:\d{1,3}(?:\.\d{1,3}){3})?(?![\w:.])/gi
const ipv4 = /(?<![\w.])\d{1,3}(?:\.\d{1,3}){3}(?![\w.])/g

/** Заменяет любой IPv4 или IPv6 в тексте словами «адрес скрыт». */
export function maskAddresses(text: string): string {
  return text.replace(ipv6, 'адрес скрыт').replace(ipv4, 'адрес скрыт')
}

/** Пояснение флага антифрода без адреса. */
export function fraudExplanation(text: string): string {
  const same = text.replace(/^С адреса\s+\S+\s+/u, `Совпадает адрес (хэш): `)
  return maskAddresses(same)
}
