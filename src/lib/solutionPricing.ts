/* Цена решения. Все суммы — целые копейки, как и баланс в базе.

   ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ЖИВЁТ ФОРМУЛА ЦЕНЫ НА КЛИЕНТЕ И СЕРВЕРЕ.
   Её зеркало в базе — `private.solution_price_kopecks_for(...)`. Меняешь
   здесь — меняй там же, иначе ученик увидит одну цену, а спишется другая.

   Раньше цена была одна на всё: 5 ₽ за любую задачу. Это было честно, пока
   задачи были одного размера. Но 6 сентября замер показал разброс
   себестоимости почти в десять раз: короткая задача по истории стоит нам
   0,24 кредита, трудная комбинаторика с починкой - 2,2 кредита, а один
   вызов дорогой модели на ней же - 6,10. Плоская цена на таком разбросе
   означает, что лёгкие задачи переплачивают за трудные.

   Что входит в цену:

   1. Постоянная часть - промпт и схема. Они одинаковы для любой задачи:
      ~2400 токенов системного промпта и ~2200 токенов схемы, это две трети
      входа даже на длинном условии. Отсюда высокий пол цены.
   2. Условие. Каждые лишние полтысячи знаков - это и вход, и, что дороже,
      более длинный разбор на выходе.
   3. Фотография. Снимок добавляет свои токены и всегда требует чтения:
      модель сначала расшифровывает условие, потом решает.
   4. Предмет. На счётных предметах проверка черновика почти всегда находит,
      к чему придраться, и включается починка - второй вызов модели. На
      предметах слова этого нет.

   Цена считается по тому, что сервер может проверить сам: длина условия,
   размер снимка, предмет. Распознавать текст на фотографии ради цены нельзя
   - число символов, присланное браузером, ничем не подтверждается, и
   заказать решение за рубль стало бы делом одной правки в консоли.

   Замеры, на которых собраны коэффициенты (6 сентября, полный решатель,
   gemini-3-6-flash-openai):

     задача                          вызовов   кредитов   нам стоит
     комбинаторика, текст, 190 зн.       1        0,74      0,37 ₽
     то же с проверкой черновика         2        2,07      1,04 ₽
     самая дорогая из замера 30 авг      3        0,51      0,22 ₽

   Кредит стоит 43 копейки. Даже худший случай - около рубля, и цена от
   четырёх рублей держит запас впятеро. Запас нужен не из жадности:
   эквайринг, налог с оборота, курс и тариф шлюза, который за три дня
   наблюдений менялся дважды. */

/* Пол цены: короткая задача текстом по предмету слова. Ниже него не
   опускаемся - постоянная часть промпта одинакова для всех. */
export const minimumSolutionPriceKopecks = 400

/* Потолок. Не потому, что дороже не бывает, а потому, что дороже нельзя
   продавать не глядя: если задача упирается в потолок, она либо огромная,
   либо это несколько задач в одной. */
export const maximumSolutionPriceKopecks = 1200

/* Цена, которую видит тот, кто ещё ничего не прислал: витрина, тарифы,
   пустая форма. Это пол, а не средняя: обещать «в среднем шесть» нельзя,
   а «от четырёх» - можно и правда. */
export const solutionPriceKopecks = minimumSolutionPriceKopecks

/* Во что нам обходится кредит шлюза. Кредит KIE стоит $0.005; при курсе
   ЦБ 85,60 ₽ за доллар это 43 копейки. Курс и тариф меняются - число
   пересматривать вместе с замером себестоимости, а не по случаю. */
export const kieCreditKopecks = 43

export type SolutionPrice = number

/* Из чего складывается цена конкретной задачи. Всё, что здесь есть, сервер
   видит своими глазами: условие он получил, снимок держит в руках, предмет
   выбран в форме из нашего же списка. */
export type SolutionPriceInput = {
  /** Длина условия в знаках. Для задачи по фото - длина пометки, обычно 0. */
  conditionLength?: number
  /** Размер снимка в байтах после сжатия в браузере. Нет фото - 0. */
  imageBytes?: number
  /** Предмет: от него зависит, ждать ли починку вторым вызовом. */
  subject?: string
}

/* Предметы, где счёт длинный и проверка черновика почти всегда просит
   пересчёта. Список тот же, что у пулов моделей (server/homeworkModels.ts),
   и по той же причине: там, где считают, второй вызов - норма. */
const countingSubjects = [
  'математик', 'алгебр', 'геометри', 'физик', 'хими', 'информатик', 'астроном',
]

function isCountingSubject(subject: string) {
  const normalized = subject.toLocaleLowerCase('ru-RU')
  return countingSubjects.some((entry) => normalized.includes(entry))
}

/* Шаг цены. Пятьдесят копеек школьник читает как «четыре пятьдесят», а
   не как «четыре рубля тридцать семь копеек»: цена должна выглядеть ценой,
   а не результатом деления. */
const priceStepKopecks = 50

function roundToStep(kopecks: number) {
  return Math.round(kopecks / priceStepKopecks) * priceStepKopecks
}

/* Цена задачи. Одна и та же функция считает и то, что показано в форме до
   отправки, и то, что спишется: расхождение между обещанным и списанным -
   худшее, что может случиться с ценой. */
export function estimateSolutionPrice(input: SolutionPriceInput = {}): SolutionPrice {
  const conditionLength = Math.max(0, Math.trunc(input.conditionLength ?? 0))
  const imageBytes = Math.max(0, Math.trunc(input.imageBytes ?? 0))
  const subject = input.subject ?? ''

  let price = minimumSolutionPriceKopecks

  // Условие сверх четырёхсот знаков: длиннее задача - длиннее разбор.
  const extraCondition = Math.max(0, conditionLength - 400)
  price += Math.floor(extraCondition / 600) * 100

  // Снимок: свои токены плюс расшифровка условия перед решением.
  if (imageBytes > 0) price += 100
  // Крупный снимок - обычно страница целиком, а не одна задача.
  if (imageBytes > 700_000) price += 100

  // Счётные предметы: починка вторым вызовом там скорее правило.
  if (isCountingSubject(subject)) price += 100

  return Math.min(
    maximumSolutionPriceKopecks,
    Math.max(minimumSolutionPriceKopecks, roundToStep(price)),
  )
}

/* Цена по умолчанию - для мест, где задачи ещё нет: витрина, кошелёк,
   пустая форма. Это по-прежнему пол цены. */
export function getSolutionPrice(): SolutionPrice {
  return solutionPriceKopecks
}
