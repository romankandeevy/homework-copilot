function normalizeTaskCondition(value) {
  return value
    .normalize('NFKC')
    .toLocaleLowerCase('ru-RU')
    .replaceAll('ё', 'е')
    .replace(/[‐‑‒–—−]/g, '-')
    .replace(/\s+(?:Рис|Puc)\.?\s*\d+\s*$/iu, '')
    .replace(/\s+/g, ' ')
    .replace(/\s*([,.;:!?])\s*/g, '$1')
    .trim()
}

function cleanCondition(value, task) {
  let condition = value
    .replace(/Скачан\s+с\s+vk\.com\/material\s*100/giu, '')
    .replace(/[СC]качан\s+[сc]\s+vk\.com\/material\s*100/giu, '')
    .replace(new RegExp(`^${task}[*+.]?\\s*`, 'u'), '')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:!?])/g, '$1')
    .trim()

  const stopPatterns = [
    /\s+Решение(?:[,.]|\s)/u,
    /\s+Доказательство(?:[,.]|\s)/u,
    /\s+Вопросы\s+для\s+повторения(?!\p{L})/u,
    /\s+\d*\s*Задачи\s+на\s+построение(?!\p{L})/u,
  ]
  const stops = stopPatterns
    .map((pattern) => condition.search(pattern))
    .filter((index) => index >= 24)
  if (stops.length > 0) condition = condition.slice(0, Math.min(...stops)).trim()
  return condition
}

function extractFigureNumbers(value) {
  const numbers = []
  const pattern = /(?:^|[^\p{L}])(?:рис|puc)[\p{L}.-]{0,8}\s*(\d{1,3})/giu
  for (const match of value.matchAll(pattern)) numbers.push(Number.parseInt(match[1], 10))
  return [...new Set(numbers.filter((figure) => figure >= 1 && figure <= 999))]
}

function resolveFigureNumbers(task, condition) {
  return figureOverrides.get(task) ?? extractFigureNumbers(condition)
}

const unresolvedFigures = []
const tasks = scan.pages
  .flatMap((page) => page.tasks)
  .sort((left, right) => left.task - right.task)
  .map((task) => {
    const condition = conditionOverrides.get(task.task) ?? cleanCondition(task.condition, task.task)
    const requestedFigures = resolveFigureNumbers(task, condition)
    const diagramRegions = requestedFigures
      .map((figure) => figures.get(figure))
      .filter(Boolean)
      // Форма region задана внешним JSON: перечислять поля — терять неизвестные.
      // eslint-disable-next-line no-map-spread
      .map((figure) => ({ figure: figure.figure, ...figure.region }))
    const missingFigures = requestedFigures.filter((figure) => !figures.has(figure))
    if (missingFigures.length > 0) unresolvedFigures.push({ task: task.task, figures: missingFigures })

    return {
      task: String(task.task),
      source_page: task.sourceRegion.page,
      condition,
      condition_normalized: normalizeTaskCondition(condition),
      ocr_confidence: task.ocrConfidence,
      has_diagram: diagramRegions.length > 0,
      source_region: task.sourceRegion,
      diagram_regions: diagramRegions,
    }
  })

if (tasks.length !== 1431) throw new Error(`Expected 1431 tasks, received ${tasks.length}`)
for (const [index, task] of tasks.entries()) {
  if (task.task !== String(index + 1)) throw new Error(`Task sequence breaks at ${index + 1}`)
  if (task.condition.length < 8) throw new Error(`Task ${task.task} has no condition`)
  if (task.source_page < 9 || task.source_page > 365) throw new Error(`Task ${task.task} has an invalid page`)
}

await writeFile(outputFile, `${JSON.stringify({ tasks, unresolvedFigures }, null, 2)}\n`, 'utf8')
process.stdout.write(`tasks=${tasks.length}\tdiagrams=${tasks.filter((task) => task.has_diagram).length}\tunresolved=${unresolvedFigures.length}\n`)
if (unresolvedFigures.length > 0) process.stdout.write(`${JSON.stringify(unresolvedFigures)}\n`)
