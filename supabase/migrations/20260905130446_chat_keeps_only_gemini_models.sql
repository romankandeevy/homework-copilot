-- Каталог ИИ-чата остаётся на семействе Gemini.
--
-- Замер 5 сентября прямыми запросами к шлюзу, одинаковый вопрос каждой
-- модели каталога:
--
--   Gemini 2.5 Flash          200, 5,7 с, ответ
--   Gemini 3 Pro              200, 7,2 с, ответ
--   Gemini 3.6 Flash          200, 4,5 с, ответ
--   GPT-5.6 Luna              поток, который наш разбор не доводит до ответа
--
-- В чате это выглядело как «Ответ не получен» при живом провайдере: путь
-- /codex отдаёт события другого формата, и текст ответа до ученика не
-- доезжал. Держать в каталоге модель, за которую берут деньги и не отдают
-- результат, нельзя.
--
-- Gemini 3.6 Flash при этом была выключена, хотя она самая быстрая из
-- рабочих. Включаем её и выключаем всё семейство GPT: лучше Gemini у
-- шлюза сейчас нет, и держать неработающий путь в каталоге незачем.
-- Сам код протокола responses остаётся - он вернётся вместе с рабочей
-- моделью этого семейства.

update private.chat_model_catalog
set is_enabled = true
where model_id = 'gemini-3-6-flash-openai';

update private.chat_model_catalog
set is_enabled = false
where model_id like 'gpt-%';
