-- Каталог чата по замеру моделей, а не по догадке.
--
-- Сначала диагноз был неверный. «Ответ не получен» у GPT-5.6 Luna я списал
-- на то, что путь /codex отдаёт поток, который наш разбор не понимает.
-- Проверка кадров SSE это опровергла: шлюз шлёт ровно
-- `response.output_text.delta`, который `chatProviders` и читает. Настоящая
-- причина была в зависшей брони генерации - разобрана в миграции
-- 20260905134541_chat_reservation_expires.sql.
--
-- Состав каталога меняем по замеру 5 сентября на задачах с известным
-- ответом (комбинаторика - 9744 и 29/405, ромб - сторона 13 см):
--
--   gemini-3-6-flash-openai   верно, 0,41 кр   - была выключена зря
--   gpt-5-6-terra             верно на голом вопросе, но под полным
--                             запросом решателя - 201 с и 9312 вместо 9744
--   gpt-5-6-luna              НЕВЕРНО          - 6864 вместо 9744
--
-- Семейство GPT выключаем целиком. Дело не в протоколе - он исправен, - а
-- в ответах: обе проверенные модели этого семейства ошибаются на школьной
-- задаче, а платит ученик независимо от того, верный ответ или нет.
-- Gemini 3.6 Flash включаем: она была выключена без причины.

update private.chat_model_catalog
set is_enabled = true
where model_id = 'gemini-3-6-flash-openai';

update private.chat_model_catalog
set is_enabled = false
where model_id like 'gpt-%';
