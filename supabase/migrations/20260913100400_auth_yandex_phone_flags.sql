-- Вход через Яндекс ID и по номеру телефона: флаги, выключенные по умолчанию.
--
-- 406-ФЗ: российский сайт авторизует пользователей из России только по
-- российскому номеру телефона, через Госуслуги, ЕБС или российский сервис
-- входа. Вход через Google убран 13 сентября, на смену ему - Яндекс ID и
-- код из СМС.
--
-- Оба способа требуют ключей, которых пока нет: Яндекс - приложения OAuth и
-- секрета подписи на Vercel, телефон - провайдера Phone и Send SMS hook в
-- Supabase и аккаунта SMS.ru. Поэтому флаги заводятся выключенными, и
-- включает их владелец в админке, когда ключи стоят.
--
-- Неизвестный флаг приложение считает включённым (featureEnabled), поэтому
-- строка обязана быть в таблице. Для этих двух флагов клиент к тому же
-- требует явного true (featureOptIn): непрочитанная конфигурация кнопки не
-- показывает.

insert into private.feature_flags (key, description, enabled)
values
  ('auth_yandex', 'Вход через Яндекс ID. Нужны YANDEX_CLIENT_ID, YANDEX_CLIENT_SECRET и AUTH_STATE_SECRET на Vercel', false),
  ('auth_phone', 'Вход по номеру телефона с кодом из СМС. Нужны провайдер Phone и Send SMS hook в Supabase, SMSRU_API_ID и SEND_SMS_HOOK_SECRET на Vercel', false)
on conflict (key) do nothing;
